import tempfile
import unittest
from pathlib import Path

from skyrimdl import mo2import
from skyrimdl.links import parse_list


def mod(mods: Path, name: str, mod_id: int = 0, files=()):
    d = mods / name
    d.mkdir(parents=True)
    if mod_id or files:
        lines = ["[General]", f"modid={mod_id}", "version=1.0", "", "[installedFiles]"]
        for i, f in enumerate(files, 1):
            lines += [f"{i}\\modid={mod_id}", f"{i}\\fileid={f}"]
        lines.append(f"size={len(files)}")
        (d / "meta.ini").write_text("\n".join(lines) + "\n", encoding="utf-8")


class BuildFromMO2Tests(unittest.TestCase):
    def test_profile_becomes_a_list(self):
        with tempfile.TemporaryDirectory() as tmp:
            inst = Path(tmp)
            (inst / "ModOrganizer.ini").write_text("[General]\nselected_profile=@ByteArray(Main)\n", encoding="utf-8")
            prof = inst / "profiles" / "Main"
            prof.mkdir(parents=True)
            # modlist.txt: highest priority first (the bottom of MO2's left pane)
            (prof / "modlist.txt").write_text(
                "# This file was automatically generated by Mod Organizer.\n"
                "+My Patch\n-Old Thing\n+Pretty Textures\n+Textures_separator\n+SkyUI\n+Hand Made\n"
                "+Interface_separator\n*DLC: Dawnguard\n", encoding="utf-8")
            mods = inst / "mods"
            for name in ("Interface_separator", "Textures_separator"):
                mod(mods, name)
            mod(mods, "Hand Made")
            mod(mods, "SkyUI", 12604, [101])
            mod(mods, "Pretty Textures", 1000, [202, 203])
            mod(mods, "Old Thing", 999, [1])
            mod(mods, "My Patch", 1000, [204])
            self.assertEqual(mo2import.profile_names(inst), ["Main"])
            built = mo2import.build_list(inst, mods, "skyrimspecialedition")
        self.assertEqual((built.mods, built.off, built.not_nexus, built.separators), (3, 1, 1, 2))
        entries, problems = parse_list(built.text)
        self.assertEqual(problems, [])
        got = [(e.section, e.mod_id, e.rule.file_ids) for e in entries]
        self.assertEqual(got, [("Interface", 12604, [101]), ("Textures", 1000, [202, 203, 204])])
        self.assertIn("# (off in MO2) https://www.nexusmods.com/skyrimspecialedition/mods/999", built.text)
        self.assertIn("# not from Nexus: Hand Made", built.text)
